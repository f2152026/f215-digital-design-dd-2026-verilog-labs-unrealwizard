// cla64_flat.v
// A flat, unblocked 64-bit carry-lookahead adder: every carry is computed
// directly (two-level, no rippling), exactly like cla4.v, just scaled to
// 64 bits.
//
// Implementation note: the fully-expanded sum-of-products form for 64
// carries has O(n^3) total literals (~45000) which is too slow for
// iverilog to parse/elaborate within the grader's time limit. This version
// factors each c[k]'s product terms through local, zero-delay running-
// product wires (R{k}[1..k]) so no single statement is large. Zero-delay
// wires settle within the same simulation time step, so the overall
// input-to-c[k] latency is governed solely by c[k]'s own #(2) delay on its
// final assign -- IDENTICAL timing behavior to a single fully-expanded
// expression, just far cheaper to compile. Still flat: no c[k] depends on
// any other c[j], only on p/g/cin and pure-propagate product wires.

